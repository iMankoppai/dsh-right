import { createRequire } from "node:module";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Build both halves.
 *
 * The host half is plain ESM; bundling it keeps the published `lib/` free of
 * relative imports while the readable source stays under `src/`.
 *
 * The browser half must be a single `window.__ModuleLoader__.load({...})`
 * registration. esbuild produces the CJS body; the wrapper below supplies the
 * `module` / `exports` pair and leaves `react`, `react/jsx-runtime`, and the
 * UI primitives to the platform's frozen seed table.
 */
async function main() {
  const esbuild = require("esbuild");

  await fs.mkdir(path.join(root, "lib"), { recursive: true });

  await esbuild.build({
    entryPoints: [path.join(root, "src/host/index.js")],
    outfile: path.join(root, "lib/index.js"),
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node22",
    legalComments: "inline",
    banner: {
      js: "/* Generated by scripts/build.mjs — edit src/host instead. */"
    }
  });

  const clientBuild = await esbuild.build({
    entryPoints: [path.join(root, "src/client/index.jsx")],
    bundle: true,
    write: false,
    format: "cjs",
    platform: "browser",
    target: "chrome120",
    jsx: "automatic",
    external: ["react", "react/jsx-runtime", "@deepseek-ai/dsh-client-ui-primitives"],
    legalComments: "none",
    banner: {
      js: "/* Generated by scripts/build.mjs — edit src/client instead. */"
    }
  });

  const body = clientBuild.outputFiles[0].text
    .split("\n")
    .map((line) => (line === "" ? "" : `    ${line}`))
    .join("\n");

  const bundle = `window.__ModuleLoader__.load({
  id: "dsh-right",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

${body}

    return module.exports;
  }
});
`;

  await fs.writeFile(path.join(root, "lib/client.js"), bundle, "utf8");
  process.stdout.write("built lib/index.js and lib/client.js\n");
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.stack ?? error.message : String(error)}\n`);
  process.exitCode = 1;
});
