import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const png = await fs.readFile(path.join(root, "assets/nav-icon.png"));
const dataUrl = `data:image/png;base64,${png.toString("base64")}`;

// The supplied artwork is a 1254px app-style illustration; at 16px its thin
// strokes dissolve into a grey blob. This is a 16px optical redraw of the same
// mouse + sliders motif, with the stroke weight of the surrounding DSH icons.
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" fill="none" stroke="white" stroke-width="1.25" stroke-linecap="round" stroke-linejoin="round"><rect x="1.6" y="1.6" width="8.1" height="11.2" rx="4.05"/><path d="M5.65 1.6v4.9M1.6 6.5h8.1"/><path d="M5.65 1.6h1.9a2.4 2.4 0 0 1 2.4 2.4v2.5H5.65Z" fill="white" stroke="none"/><path d="M9.7 10.4h5.5"/><circle cx="12.4" cy="10.4" r="1.25" fill="white" stroke="none"/><path d="M9.7 13h5.3"/><circle cx="11.5" cy="13" r="1.25" fill="white" stroke="none"/></svg>`;
const maskUrl = `data:image/svg+xml,${encodeURIComponent(svg)}`;

const source = `// Generated by scripts/build-nav-icon.mjs from assets/nav-icon.png.\n// Re-run it after replacing the source icon.\nexport const NAV_ICON_DATA_URL = ${JSON.stringify(dataUrl)};\n// 16px optical redraw of the same motif (1.25px strokes, like DSH's icons).\nexport const NAV_ICON_MASK_URL = ${JSON.stringify(maskUrl)};\n`;
await fs.writeFile(path.join(root, "src/client/nav-icon.js"), source, "utf8");
process.stdout.write(`wrote src/client/nav-icon.js (${maskUrl.length} byte mask URL)\n`);
